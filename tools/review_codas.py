def main():
    vocab = json.loads((ROOT / 'data/lexicon.json').read_text(encoding='utf-8'))['vocabulary']
    marked = {r['id']: r for r in vocab if r['nrs'][-1] not in 'aeiouylrnms'}
    if set(APPROVED) & set(REJECTED) or set(APPROVED) | set(REJECTED) != marked.keys():
        raise ValueError({'missing': sorted(marked.keys()-(set(APPROVED)|set(REJECTED))),
                          'extra': sorted((set(APPROVED)|set(REJECTED))-marked.keys())})
    baseline = json.loads((ROOT / 'audit/runs/2026-10-15-reviewed/before/coda_reviews.json').read_text(encoding='utf-8'))
    hashes = {r['lexiconId']: r['reviewedAgainstEntryHash'] for r in baseline['entries']}
    rows, candidates = [], []
    all_roots = {r['nrs'] for r in vocab}
    for id_, entry in marked.items():
        if hashes[id_] != entry_hash(entry):
            raise ValueError(f'Entry changed since this semantic review: {id_}')
        approved = id_ in APPROVED
        rule, reason = APPROVED[id_] if approved else ('neither', REJECTED[id_])
        rows.append({'lexiconId': id_, 'nrs': entry['nrs'], 'finalConsonant': entry['nrs'][-1],
                     'decision': 'approved' if approved else 'rejected', 'ruleId': 'SOP.CHK08.'+rule,
                     'reason': reason, 'reviewer': 'Codex', 'reviewType': 'AI semantic review',
                     'reviewedAgainstEntryHash': entry_hash(entry)})
        if not approved:
            suggestions = [entry['nrs'][:-1]+c for c in 'nrlms'
                           if entry['nrs'][:-1]+c not in all_roots and entry['nrs'][-2] != c]
            candidates.append({'lexiconId': id_, 'currentNrs': entry['nrs'], 'meaningJa': entry['meaningJa'],
                               'candidates': [{'nrs': s, 'phonemeSequence': expected_ipa(s)} for s in suggestions],
                               'applied': False, 'note': '未採用。語源・派生・音節構造・多言語類似と候補間の衝突を要確認。'})
    dump(ROOT / 'data/audit/coda_reviews.json', {'scope': 'coda-semantic-1: 堅固な物体・剛性支持構造、または衝突・放出等の瞬発事象。比喩・専門語というだけでは免除しない。', 'entries': rows})
    dump(ROOT / 'data/audit/coda_repair_candidates.json', {'status': 'draft-not-applied', 'entries': candidates})
    print(f'Individually reviewed {len(rows)}: approved {len(APPROVED)}, rejected {len(REJECTED)}; no roots renamed.')


if __name__ == '__main__':
    main()
